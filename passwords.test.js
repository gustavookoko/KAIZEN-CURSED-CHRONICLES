'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { passwordHash, verifyPassword } = require('../src/passwords');

test('verifies hashes generated by the original crypto.scrypt format', () => {
  const password = 'synthetic-test-password';
  const salt = crypto.randomBytes(16).toString('hex');
  const legacyHash = crypto.scryptSync(password, salt, 64).toString('hex');
  assert.equal(passwordHash(password, salt), legacyHash);
  assert.equal(verifyPassword(password, salt, legacyHash), true);
  assert.equal(verifyPassword('wrong-password', salt, legacyHash), false);
});

test('rejects malformed stored hashes safely', () => {
  assert.equal(verifyPassword('password123', 'salt', 'not-a-hash'), false);
});
